-- Rujukan skema Shared Edition.
-- Jika jadual ini sudah berjaya dibuat, JANGAN jalankan semula tanpa menyemak dahulu.
create table if not exists public.tracker_members (
  user_id uuid primary key references auth.users(id) on delete cascade
);
create table if not exists public.prayer_entries (
  id bigint generated by default as identity primary key,
  prayer_date date not null,
  prayer_name text not null check (prayer_name in ('Subuh','Zohor','Asar','Maghrib','Isyak')),
  status text not null default 'pending' check (status in ('pending','done','missed')),
  prayed_at time,
  unique (prayer_date, prayer_name)
);
create table if not exists public.monthly_reflections (
  id bigint generated by default as identity primary key,
  month date not null unique,
  notes text not null default '',
  improvement text not null default ''
);
alter table public.tracker_members enable row level security;
alter table public.prayer_entries enable row level security;
alter table public.monthly_reflections enable row level security;
create or replace function public.is_tracker_member()
returns boolean language sql security definer stable set search_path = ''
as $$
  select exists (select 1 from public.tracker_members where user_id = (select auth.uid()));
$$;
revoke all on function public.is_tracker_member() from public;
grant execute on function public.is_tracker_member() to authenticated;
create policy "Members read prayers" on public.prayer_entries for select to authenticated using ((select public.is_tracker_member()));
create policy "Members add prayers" on public.prayer_entries for insert to authenticated with check ((select public.is_tracker_member()));
create policy "Members update prayers" on public.prayer_entries for update to authenticated using ((select public.is_tracker_member())) with check ((select public.is_tracker_member()));
create policy "Members read reflections" on public.monthly_reflections for select to authenticated using ((select public.is_tracker_member()));
create policy "Members add reflections" on public.monthly_reflections for insert to authenticated with check ((select public.is_tracker_member()));
create policy "Members update reflections" on public.monthly_reflections for update to authenticated using ((select public.is_tracker_member())) with check ((select public.is_tracker_member()));
grant select, insert, update on public.prayer_entries, public.monthly_reflections to authenticated;
grant usage, select on all sequences in schema public to authenticated;
